import { readFile, writeFile } from 'node:fs/promises';

/**
 * Emits public/theme-boot.js — a tiny classic script the shell loads synchronously so the
 * stored palette is on the document before first paint.
 *
 * It is generated rather than hand-written because the boot path duplicates decisions that
 * already live in src/theme.ts (the storage key, the theme ids, the stored-then-system
 * resolution order). A hand-maintained copy of that logic drifts the first time a theme is
 * added and nobody notices, because the only symptom is a flash.
 *
 * The CSP forbids inline scripts (`script-src 'self'`), which is why this is a real file rather
 * than a `<script>` block like the usual no-flash trick.
 */

export async function buildThemeBoot() {
const themeSource = await readFile(new URL('../src/theme.ts', import.meta.url), 'utf8');
const cssSource = await readFile(new URL('../src/index.css', import.meta.url), 'utf8');

const storageKey = themeSource.match(/THEME_STORAGE_KEY = '([^']+)'/)?.[1];
if (!storageKey) throw new Error('Could not read THEME_STORAGE_KEY from src/theme.ts.');

const optionIds = [...themeSource.matchAll(/\{ id: '([^']+)', label:/g)].map(([, id]) => id);
if (optionIds.length === 0) throw new Error('Could not read THEME_OPTIONS from src/theme.ts.');

const packageThemes = await Promise.all(optionIds
  .filter((id) => id !== 'progros')
  .map(async (id) => {
    const theme = JSON.parse(await readFile(
      new URL(`../node_modules/@williamzujkowski/oklch-terminal-themes/data/by-name/${id}.json`, import.meta.url),
      'utf8',
    ));
    return [id, { bg: theme.colors.background.oklchCss, fg: theme.colors.foreground.oklchCss, meta: theme.colors.background.hex }];
  }));

// progros is authored in CSS rather than shipped by the theme package, so its two critical
// colours are read back out of the stylesheet instead of invented here. A regex over CSS is
// only safe because a test asserts the generated file matches a fresh run of this script.
const progrosBlock = cssSource.match(/\[data-theme='progros'\]\s*\{([\s\S]*?)\}/)?.[1];
if (!progrosBlock) throw new Error('Could not find the progros theme block in src/index.css.');
const progrosBg = progrosBlock.match(/--terminal-background:\s*([^;]+);/)?.[1]?.trim();
const progrosFg = progrosBlock.match(/--terminal-foreground:\s*([^;]+);/)?.[1]?.trim();
if (!progrosBg || !progrosFg) throw new Error('progros theme block is missing background or foreground.');

const palettes = Object.fromEntries([
  ...packageThemes,
  ['progros', { bg: progrosBg, fg: progrosFg, meta: null }],
]);

const defaultDark = optionIds.includes('remarque-dark') ? 'remarque-dark' : optionIds[0];
const defaultLight = optionIds.includes('remarque-light') ? 'remarque-light' : optionIds[0];

const boot = `// GENERATED by scripts/generate-theme-boot.mjs — do not edit.
// Runs before first paint so a stored palette does not flash the static fallback.
(function () {
  var PALETTES = ${JSON.stringify(palettes, null, 2).split('\n').join('\n  ')};
  var KEY = ${JSON.stringify(storageKey)};
  var stored = null;
  try {
    stored = window.localStorage.getItem(KEY);
  } catch {
    // Storage denied. Fall through to the system preference exactly as the app does; a theme
    // is a preference, not a reason to fail loading.
    stored = null;
  }
  var prefersDark = false;
  try {
    prefersDark = window.matchMedia('(prefers-color-scheme: dark)').matches;
  } catch {
    prefersDark = false;
  }
  var theme = Object.prototype.hasOwnProperty.call(PALETTES, stored)
    ? stored
    : (prefersDark ? ${JSON.stringify(defaultDark)} : ${JSON.stringify(defaultLight)});
  var palette = PALETTES[theme];
  if (!palette) return;

  var root = document.documentElement;
  root.dataset.theme = theme;
  if (theme !== 'progros') root.dataset.terminalTheme = theme;
  root.style.setProperty('--terminal-background', palette.bg);
  root.style.setProperty('--terminal-foreground', palette.fg);
  if (palette.meta) {
    var meta = document.querySelector('meta[name="theme-color"]');
    if (meta) meta.setAttribute('content', palette.meta);
  }
})();
`;

  return { boot, count: Object.keys(palettes).length };
}

export const THEME_BOOT_URL = new URL('../public/theme-boot.js', import.meta.url);

// Only write when invoked directly, so the test can compare without touching the tree.
if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  const { boot, count } = await buildThemeBoot();
  await writeFile(THEME_BOOT_URL, boot);
  console.log(`Generated theme boot for ${count} palettes.`);
}
